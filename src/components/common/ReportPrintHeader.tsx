import React, { useState, useEffect } from 'react';
import { EthioReLogo } from './EthioReLogo';
import { storageService } from '../../services/storage';

export interface ReportPrintHeaderProps {
  title: string;
  subtitle?: string;
  filters?: Array<{ label: string; value: string }>;
  recordCount?: number;
}

export const ReportPrintHeader: React.FC<ReportPrintHeaderProps> = ({
  title,
  subtitle,
  filters = [],
  recordCount,
}) => {
  const [companyInfo, setCompanyInfo] = useState(() => storageService.getCompanyInfo());
  const currentUser = storageService.getCurrentUser();

  useEffect(() => {
    const handleUpdate = () => {
      setCompanyInfo(storageService.getCompanyInfo());
    };
    window.addEventListener('ethiore_company_update', handleUpdate);
    window.addEventListener('ethiore_storage_update', handleUpdate);
    return () => {
      window.removeEventListener('ethiore_company_update', handleUpdate);
      window.removeEventListener('ethiore_storage_update', handleUpdate);
    };
  }, []);

  const now = new Date();
  const dateStr = now.toLocaleDateString('en-GB', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  });
  const timeStr = now.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  return (
    <div className="print-only mb-6 pb-4 border-b-2 border-[#186382] text-slate-900">
      {/* Top Organization Official Branding Header */}
      <div className="flex items-center justify-between gap-4">
        <div className="flex items-center space-x-3">
          <EthioReLogo size="lg" variant="full" theme="light" />
        </div>
        <div className="text-right text-[10px] text-slate-600 leading-tight">
          <div className="font-bold text-[#186382] text-xs">
            {companyInfo?.name || 'ETHIOPIAN REINSURANCE S.C.'}
          </div>
          <div>Human Resource Management System</div>
          <div>EthioRe Tower, Africa Avenue (Bole Road), Kirkos, Addis Ababa</div>
          {companyInfo?.tin && (
            <div className="text-[9px] text-slate-500 font-mono mt-0.5">TIN: {companyInfo.tin}</div>
          )}
        </div>
      </div>

      {/* Report Title & Context */}
      <div className="mt-4 pt-3 border-t border-slate-200 flex items-end justify-between gap-4">
        <div>
          <h1 className="text-base font-bold text-[#186382] uppercase tracking-wide">
            {title}
          </h1>
          {subtitle && (
            <p className="text-xs text-slate-600 font-medium mt-0.5">{subtitle}</p>
          )}
        </div>

        <div className="text-right text-[10px] text-slate-600 space-y-0.5 shrink-0">
          <div>
            <span className="font-semibold text-slate-700">Date Generated:</span> {dateStr} {timeStr}
          </div>
          <div>
            <span className="font-semibold text-slate-700">Generated By:</span> {currentUser.displayName || 'Authorized User'} ({currentUser.role || 'Staff'})
          </div>
          {recordCount !== undefined && (
            <div>
              <span className="font-semibold text-slate-700">Total Records:</span> {recordCount}
            </div>
          )}
        </div>
      </div>

      {/* Applied Filters Criteria */}
      {filters.length > 0 && (
        <div className="mt-2.5 p-2 bg-slate-50 border border-slate-200 rounded text-[10px] flex flex-wrap items-center gap-x-4 gap-y-1">
          <span className="font-bold uppercase tracking-wider text-slate-600">
            Selected Filters:
          </span>
          {filters.map((f, i) => (
            <span key={i} className="text-slate-800">
              <strong className="text-slate-600">{f.label}:</strong> {f.value}
            </span>
          ))}
        </div>
      )}
    </div>
  );
};
