import React from 'react';
import { EthioReLogo } from './EthioReLogo';
import { storageService } from '../../services/storage';

export interface ReportPrintHeaderProps {
  title: string;
  subtitle?: string;
  filters?: Array<{ label: string; value: string }>;
  recordCount?: number;
}

export const ReportPrintHeader: React.FC<ReportPrintHeaderProps> = ({
  title,
  subtitle,
  filters = [],
  recordCount,
}) => {
  const currentUser = storageService.getCurrentUser();
  const companyInfo = storageService.getCompanyInfo();
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-GB', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  });
  const timeStr = now.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  return (
    <div className="print-only mb-6 pb-4 border-b-2 border-[#186382] text-slate-900">
      {/* Top Organization Official Branding Header */}
      <div className="flex items-center justify-between">
        <EthioReLogo size="md" variant="full" theme="light" />
        <div className="text-right text-[10px] text-slate-600 leading-tight">
          <div className="font-bold text-[#186382] text-xs">
            {companyInfo?.name || 'Ethiopian Reinsurance S.C.'}
          </div>
          <div>Human Resource Management System</div>
          <div>EthioRe Tower, Africa Avenue, Kirkos, Addis Ababa</div>
        </div>
      </div>

      {/* Report Title & Context */}
      <div className="mt-4 pt-3 border-t border-slate-200 flex items-end justify-between">
        <div>
          <h1 className="text-base font-bold text-[#186382] uppercase tracking-wide">
            {title}
          </h1>
          {subtitle && (
            <p className="text-xs text-slate-600 font-medium mt-0.5">{subtitle}</p>
          )}
        </div>

        <div className="text-right text-[10px] text-slate-600 space-y-0.5">
          <div>
            <span className="font-semibold text-slate-700">Date Generated:</span> {dateStr} {timeStr}
          </div>
          <div>
            <span className="font-semibold text-slate-700">Generated By:</span> {currentUser.displayName} ({currentUser.role})
          </div>
          {recordCount !== undefined && (
            <div>
              <span className="font-semibold text-slate-700">Total Records:</span> {recordCount}
            </div>
          )}
        </div>
      </div>

      {/* Applied Filters Criteria */}
      {filters.length > 0 && (
        <div className="mt-2.5 p-2 bg-slate-50 border border-slate-200 rounded text-[10px] flex flex-wrap items-center gap-x-4 gap-y-1">
          <span className="font-bold uppercase tracking-wider text-slate-600">
            Selected Filters:
          </span>
          {filters.map((f, i) => (
            <span key={i} className="text-slate-800">
              <strong className="text-slate-600">{f.label}:</strong> {f.value}
            </span>
          ))}
        </div>
      )}
    </div>
  );
};
